const REVERSE = new Map<Codepage, Map<number, number>>()

/** Byte for a code point in the page, or -1 when the page cannot represent it. ASCII printable maps to itself. */
export function byteFor(codepage: Codepage, cp: number): number {
  if (cp >= 0x20 && cp < 0x7f) return cp
  let rev = REVERSE.get(codepage)
  if (!rev) {
    rev = new Map()
    HIGH[codepage].forEach((c, i) => {
      if (c !== 0 && !rev!.has(c)) rev!.set(c, 0x80 + i)
    })
    REVERSE.set(codepage, rev)
  }
  return rev.get(cp) ?? -1
}
